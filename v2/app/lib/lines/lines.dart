// The production-lines section: 15 classic-control projects (no PLC), from a simple
// conveyor to a full packing line. Each one is a machine modelled in Blender
// (v2/models/machines.py) on the panel lab's bench, and a circuit the student wires
// by hand on a real panel, then runs and tests against the machine.
//
// A line with a [circuit] opens as a panel-lab exercise (devices mounted, schematic
// and tasks beside, wiring check and solution); the others are announced as coming.

class ProdLine {
  final int n, level;
  final String title, short, story;

  /// the machine on the bench (lab part key), for the card picture
  final String machine;

  /// what the student builds, in order
  final List<String> steps;

  /// the panel's main devices
  final List<String> parts;

  /// faults the student can practise finding with the meters
  final List<String> faults;

  /// the exercise circuit (lib/sim/circuits.dart kLineCircuits), null = coming soon
  final String? circuit;
  const ProdLine(this.n, this.level, this.short, this.title, this.story,
      {required this.machine, required this.steps, required this.parts, required this.faults, this.circuit});

  bool get ready => circuit != null;
}

