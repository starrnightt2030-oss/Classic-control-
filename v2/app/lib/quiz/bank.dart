/// symbol recognition questions, generated from the schematic library
List<QQ> _symbolQuestions() {
  final keys = kSyms.keys.where((k) => kSyms[k]!.role != SymRole.source).toList();
  final out = <QQ>[];
  for (var i = 0; i < keys.length; i++) {
    final d = kSyms[keys[i]]!;
    final others = <String>[];
    for (var j = 1; others.length < 3 && j < keys.length; j++) {
      final o = kSyms[keys[(i + j * 3) % keys.length]]!.nameAr;
      if (o != d.nameAr && !others.contains(o)) others.add(o);
    }
    out.add(QQ('sym_${d.key}', 'sym', 'ما اسم هذا الرمز في المخطط؟', [d.nameAr, ...others], 'هذا رمز «${d.nameAr}» حسب IEC 60617.', fig: 'sym:${d.key}'));
  }
  return out;
}

