/// One section of a lesson: text, points, an optional 3D model to turn and take
/// apart, key facts, a formula with its worked example, and the usual mistakes.
class LessonPart {
  final String h;
  final String body;
  final List<String> points;
  final String? model; // assets/models/<model>.glb (3D) and assets/renders/<model>.webp
  final String modelName;
  final List<(String, String)> facts; // a two-column table
  final String formula;
  final String example; // a worked example of the formula
  final List<String> mistakes;
  const LessonPart(this.h, this.body,
      {this.points = const [], this.model, this.modelName = '', this.facts = const [], this.formula = '', this.example = '', this.mistakes = const []});
}

class QuizQ {
  final String q;
  final List<String> options;
  final int answer;
  final String why;
  const QuizQ(this.q, this.options, this.answer, this.why);
}

class Lesson {
  final String id;
  final String title;
  final String sub;
  final String cover; // model render used as the cover
  final int minutes;
  final List<LessonPart> parts;
  final List<String> circuits; // related circuits to practise on the simulator
  final List<QuizQ> quiz;
  const Lesson(this.id, this.title, this.sub, this.cover, this.minutes, this.parts, {this.circuits = const [], this.quiz = const []});
}

