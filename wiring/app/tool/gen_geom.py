"""assets/board/board_sprites.json -> lib/data/board_geom.dart (sizes and terminals in mm).

Run after wiring/models/render_board.py:  python3 tool/gen_geom.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(HERE, "..")
src = json.load(open(os.path.join(APP, "assets", "board", "board_sprites.json")))
ppm = src.pop("_ppm")
# model terminal names -> the simulator's terminal ids
RENAME = {
    "mcb_1p": {"1": "in", "2": "out"},
    "rccb": {"1": "Li", "2": "Lo", "N": "Ni", "N2": "No"},
    "kwh_meter": {"1": "Li", "3": "Lo", "4": "Ni", "6": "No"},
}
out = ["// GENERATED by tool/gen_geom.py from assets/board/board_sprites.json. Do not edit.",
       "import 'dart:ui' show Offset;", "",
       "class SpriteGeom {",
       "  final double w, h; // mm",
       "  final int px, py; // sprite pixels",
       "  final Map<String, Offset> terms; // mm from the top-left corner",
       "  const SpriteGeom(this.w, this.h, this.px, this.py, this.terms);",
       "}", "",
       "const kSpritePpm = %s;" % ppm, "",
       "const spriteGeom = <String, SpriteGeom>{"]
for name in sorted(src):
    d = src[name]
    ren = RENAME.get(name, {})
    terms = ", ".join("'%s': Offset(%.1f, %.1f)" % (ren.get(k, k), x / ppm, y / ppm) for k, (x, y) in sorted(d["terms"].items()))
    out.append("  '%s': SpriteGeom(%.1f, %.1f, %d, %d, {%s})," % (name, d["w"] / ppm, d["h"] / ppm, d["w"], d["h"], terms))
out.append("};")
open(os.path.join(APP, "lib", "data", "board_geom.dart"), "w").write("\n".join(out) + "\n")
print(len(src), "sprites")
